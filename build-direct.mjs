// 將本機模組合併為一般script，讓file://雙擊也可使用；保留ES Modules原始碼。
import {readFile,writeFile} from 'node:fs/promises';
const read=name=>readFile(`js/${name}.js`,'utf8');
const strip=s=>s.replace(/^import .*?;\r?\n/gm,'').replace(/\bexport /g,'');
const files=await Promise.all(['recipe-data','recipe-engine','ai-service','storage','ui'].map(read));
const kitchen=strip(await read('kitchen3d'));
let main=strip(await read('main'));
// main.js 的命名匯入別名在一般script中明確宣告。
main='const e=escapeHTML;\n'+main;
main=main.replace("await import('./kitchen3d.js')",`await (async()=>{const [T,{OrbitControls},{RoundedBoxGeometry},{GLTFLoader}]=await Promise.all([import('three'),import('three/addons/controls/OrbitControls.js'),import('three/addons/geometries/RoundedBoxGeometry.js'),import('three/addons/loaders/GLTFLoader.js')]);\n${kitchen}\nreturn {createKitchen};})()`);
await writeFile('js/direct-app.js','// Generated by node build-direct.mjs\n(async()=>{\n'+files.map(strip).join('\n')+'\n'+main+'\n})().catch(error=>{console.error(error);document.querySelector("#scene-status").textContent="啟動失敗，請使用一鍵啟動檔重新開啟。"});\n');
const html=await readFile('index.html','utf8');await writeFile('index.html',html.replace('<script type="module" src="js/main.js"></script>','<script src="js/direct-app.js"></script>'));
